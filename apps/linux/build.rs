//! Linux: compiles the QML module, the Rust bridges and the C++ shim with cxx-qt-build (cargo
//! only, no CMake). Elsewhere it does nothing: the crate is a stub (src/main.rs).
fn main() {
    #[cfg(target_os = "linux")]
    qt::build();
}

#[cfg(target_os = "linux")]
mod qt {
    use std::os::unix::fs::PermissionsExt;
    use std::path::{Path, PathBuf};
    use std::process::Command;

    /// The qmake qt-build-utils would pick: `$QMAKE`, else the first `qmake6` or `qmake` on PATH.
    fn real_qmake() -> PathBuf {
        if let Some(qmake) = std::env::var_os("QMAKE") {
            return PathBuf::from(qmake);
        }
        let path = std::env::var_os("PATH").unwrap_or_default();
        ["qmake6", "qmake"]
            .iter()
            .find_map(|name| {
                std::env::split_paths(&path)
                    .map(|dir| dir.join(name))
                    .find(|candidate| candidate.is_file())
            })
            .unwrap_or_else(|| panic!("no qmake6 or qmake on PATH, and QMAKE is not set"))
    }

    fn qmake_query(qmake: &Path, var: &str) -> String {
        let out = Command::new(qmake)
            .args(["-query", var])
            .env_clear()
            .output()
            .unwrap_or_else(|e| panic!("{} -query {var}: {e}", qmake.display()));
        String::from_utf8_lossy(&out.stdout).trim().to_owned()
    }

    /// `path` in single quotes, for sh.
    fn quoted(path: &Path) -> String {
        let text = path.to_str().expect("a Qt or OUT_DIR path is not UTF-8");
        assert!(!text.contains('\''), "a quote in {text}");
        format!("'{text}'")
    }

    fn write_script(path: &Path, text: &str) {
        std::fs::write(path, text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755))
            .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    }

    /// Makes qmlcachegen compile the QML to bytecode only (`--only-bytecode`, the switch Qt
    /// documents for CMake's QT_QMLCACHEGEN_ARGUMENTS). Its default output adds C++ for the
    /// bindings it understands, and that C++ calls `QQmlPrivate::AOTCompiledContext`, Qt's
    /// private API, versioned `Qt_6.<minor>_PRIVATE_API`: the binary would then run on that
    /// one Qt minor version only. Bytecode needs no private symbol, and when Qt's V4 data
    /// version changes, the engine loads the .qml sources (kept in the resources) instead.
    ///
    /// cxx-qt-build 0.10 has no switch for this, but qt-build-utils looks Qt's tools up through
    /// `qmake -query QT_HOST_LIBEXECS/get` first. So QMAKE names a qmake that answers that one
    /// query with a directory holding only a qmlcachegen wrapper; every other query goes to the
    /// real qmake, and every other tool is found where it was. Returns the wrapper's call log.
    fn bytecode_only_qmlcachegen() -> PathBuf {
        let qmake = real_qmake();
        // qt-build-utils' own search order.
        let qmlcachegen = [
            "QT_HOST_LIBEXECS/get",
            "QT_HOST_LIBEXECS",
            "QT_HOST_BINS/get",
            "QT_HOST_BINS",
            "QT_INSTALL_LIBEXECS/get",
            "QT_INSTALL_LIBEXECS",
            "QT_INSTALL_BINS/get",
            "QT_INSTALL_BINS",
        ]
        .iter()
        .map(|var| qmake_query(&qmake, var))
        .filter(|dir| !dir.is_empty())
        .map(|dir| PathBuf::from(dir).join("qmlcachegen"))
        .find(|candidate| candidate.is_file())
        .unwrap_or_else(|| panic!("{} knows no qmlcachegen", qmake.display()));

        let dir =
            PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("bytecode-only");
        let libexec = dir.join("libexec");
        std::fs::create_dir_all(&libexec).unwrap_or_else(|e| panic!("{}: {e}", libexec.display()));
        let log = dir.join("qmlcachegen.log");
        if let Err(e) = std::fs::remove_file(&log)
            && e.kind() != std::io::ErrorKind::NotFound
        {
            panic!("{}: {e}", log.display());
        }
        // qt-build-utils runs Qt's tools with an empty environment: absolute paths only.
        write_script(
            &libexec.join("qmlcachegen"),
            &format!(
                "#!/bin/sh\n\
                 # Generated by apps/linux/build.rs: Qt's qmlcachegen, bytecode only.\n\
                 echo \"--only-bytecode $*\" >>{log}\n\
                 exec {qmlcachegen} --only-bytecode \"$@\"\n",
                log = quoted(&log),
                qmlcachegen = quoted(&qmlcachegen),
            ),
        );
        let wrapper_qmake = dir.join("qmake");
        write_script(
            &wrapper_qmake,
            &format!(
                "#!/bin/sh\n\
                 # Generated by apps/linux/build.rs: {name}, but Qt's tools are looked up\n\
                 # next to the bytecode-only qmlcachegen first.\n\
                 if [ \"$*\" = \"-query QT_HOST_LIBEXECS/get\" ]; then\n\
                 \x20 echo {libexec}\n\
                 else\n\
                 \x20 exec {qmake} \"$@\"\n\
                 fi\n",
                name = qmake.display(),
                libexec = quoted(&libexec),
                qmake = quoted(&qmake),
            ),
        );
        println!("cargo::rerun-if-env-changed=QMAKE");
        // SAFETY: the build script has one thread here; cxx-qt-build reads QMAKE in build().
        unsafe { std::env::set_var("QMAKE", &wrapper_qmake) };
        log
    }

    /// `dir/*.ext`, sorted; a missing directory is empty.
    fn sources(dir: &str, ext: &str) -> Vec<PathBuf> {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return Vec::new();
        };
        let mut found: Vec<PathBuf> = entries
            .filter_map(Result::ok)
            .map(|entry| entry.path())
            .filter(|path| path.extension().is_some_and(|e| e == ext))
            .collect();
        found.sort();
        found
    }

    /// A Rust file is a bridge when a line starts (after indentation) with `#[cxx_qt::bridge`
    /// or `#[cxx::bridge`.
    fn is_bridge(text: &str) -> bool {
        text.lines().any(|line| {
            let line = line.trim_start();
            line.starts_with("#[cxx_qt::bridge") || line.starts_with("#[cxx::bridge")
        })
    }

    pub fn build() {
        for dir in ["src", "qml", "cpp"] {
            println!("cargo::rerun-if-changed={dir}"); // new files are picked up
        }
        let qmlcachegen_log = bytecode_only_qmlcachegen();
        let bridges = sources("src", "rs").into_iter().filter(|path| {
            let text = std::fs::read_to_string(path)
                .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
            is_bridge(&text)
        });
        let builder = cxx_qt_build::CxxQtBuilder::new_qml_module(
            cxx_qt_build::QmlModule::new("org.w3cdotorg.ressac")
                .qml_files(sources("qml", "qml"))
                .depend("QtQuick"),
        )
        .files(bridges)
        .include_dir("cpp")
        .cpp_files(sources("cpp", "cpp"))
        .qt_module("Quick")
        .qt_module("QuickControls2")
        .qt_module("Widgets")
        .qt_module("WebEngineQuick")
        .qt_module("WebEngineCore")
        .qt_module("WebChannel");
        // SAFETY: only adds one warning switch to the builder's own cc::Build. gcc 16 prints
        // -Wsfinae-incomplete for Qt headers next to rust/cxx.h (spike gotcha 7); not ours to fix.
        unsafe {
            builder.cc_builder(|cc| {
                cc.flag_if_supported("-Wno-sfinae-incomplete");
            })
        }
        .build();

        // A cxx-qt upgrade that finds qmlcachegen another way must fail here, not ship C++.
        let calls = std::fs::read_to_string(&qmlcachegen_log).unwrap_or_default();
        assert!(
            calls.lines().any(|call| call.contains("--resource-path")),
            "qt-build-utils compiled the QML without the bytecode-only qmlcachegen; calls: {calls:?}"
        );
        for call in calls.lines() {
            println!("qmlcachegen {call}"); // in the build script's output (cargo build -vv)
        }
    }
}
